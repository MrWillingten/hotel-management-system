"""Generate the UML class diagrams from the source code (Graphviz DOT).

    python docs/diagrams/class_diagrams.py      # writes the three *.dot files
    make -C docs/diagrams                        # renders SVG and PDF

Attributes, types, enumeration literals and operations are read from the
code with `ast`, so the diagrams cannot drift from it: after a change, run
the script again. Only the relationships (with their multiplicities) are
written here by hand, from the identifiers the classes hold (`guest_id`,
`room_id`...) and the lists they own (`rooms`, `nights`...).

Notation (UML): «stereotype», + public operation, / derived attribute (a
Python property), {abstract} in italics, — association, ◆ composition,
◇ aggregation, ▷ generalisation, ⇢ dependency.
"""

from __future__ import annotations

import ast
import html
from dataclasses import dataclass, field
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[1] / "src" / "hotel"

INK, ACCENT, PAPER, SOFT = "#3b2f2a", "#a0522d", "#fdf6ee", "#f3e7da"


# ---------------------------------------------------------------- reading the code
@dataclass
class UmlClass:
    name: str
    module: str
    bases: list[str]
    attributes: list[str] = field(default_factory=list)
    operations: list[str] = field(default_factory=list)
    literals: list[str] = field(default_factory=list)
    abstract: bool = False

    @property
    def is_enum(self) -> bool:
        return any("Enum" in b for b in self.bases)


def read_classes(*packages: str) -> dict[str, UmlClass]:
    found: dict[str, UmlClass] = {}
    for package in packages:
        for path in sorted((SRC / package).glob("*.py")):
            module = f"{package}.{path.stem}".lstrip(".")
            for node in ast.parse(path.read_text(encoding="utf-8")).body:
                if isinstance(node, ast.ClassDef):
                    found[node.name] = _read(node, module)
    return found


def _short(annotation: str) -> str:
    return annotation.replace("datetime.", "").replace("typing.", "")


def _read(node: ast.ClassDef, module: str) -> UmlClass:
    bases = [ast.unparse(b) for b in node.bases]
    uml = UmlClass(node.name, module, bases, abstract="ABC" in bases)
    for item in node.body:
        if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
            name = item.target.id
            if not name.startswith("_"):
                uml.attributes.append(f"{name}: {_short(ast.unparse(item.annotation))}")
        elif isinstance(item, ast.Assign) and uml.is_enum:
            uml.literals.append(ast.unparse(item.targets[0]))
        elif isinstance(item, ast.FunctionDef) and not item.name.startswith("_"):
            decorators = [ast.unparse(d) for d in item.decorator_list]
            returns = f": {_short(ast.unparse(item.returns))}" if item.returns else ""
            if "property" in decorators:
                uml.attributes.append(f"/{item.name}{returns}")
            else:
                params = [a.arg for a in item.args.args if a.arg not in ("self", "cls")]
                params += [f"{a.arg}" for a in item.args.kwonlyargs]
                prefix = "{static} " if {"staticmethod", "classmethod"} & set(decorators) else ""
                uml.operations.append(f"{prefix}+{item.name}({', '.join(params)}){returns}")
            if "abstractmethod" in decorators:
                uml.abstract = True
    return uml


# ---------------------------------------------------------------- drawing
def _esc(text: str) -> str:
    return html.escape(text, quote=False)


def class_node(uml: UmlClass, *, stereotype: str = "", fill: str = PAPER, full: bool = True) -> str:
    title = f"<I>{_esc(uml.name)}</I>" if uml.abstract else _esc(uml.name)
    rows = []
    if uml.is_enum:
        stereotype = "enumeration"
    if stereotype:
        rows.append(f'<TR><TD><FONT POINT-SIZE="8">«{stereotype}»</FONT></TD></TR>')
    rows.append(f"<TR><TD><B>{title}</B></TD></TR>")
    if uml.abstract:
        rows.append('<TR><TD><FONT POINT-SIZE="8">{abstract}</FONT></TD></TR>')
    if full:
        body = uml.literals if uml.is_enum else uml.attributes
        rows.append(_compartment(body))
        if not uml.is_enum:
            rows.append(_compartment(uml.operations))
    table = "".join(rows)
    return (
        f'  {uml.name} [label=<<TABLE BORDER="1" CELLBORDER="0" CELLSPACING="0" '
        f'CELLPADDING="3" COLOR="{ACCENT}" BGCOLOR="{fill}">{table}</TABLE>>];\n'
    )


def _compartment(lines: list[str]) -> str:
    text = '<BR ALIGN="LEFT"/>'.join(_esc(line) for line in lines) or " "
    return f'<TR><TD SIDES="T" COLOR="{ACCENT}" ALIGN="LEFT" BALIGN="LEFT">{text}<BR ALIGN="LEFT"/></TD></TR>'


HEADER = """digraph {name} {{
  // Generated by docs/diagrams/class_diagrams.py from the source code: do not edit by hand.
  graph [fontname="Helvetica", fontsize=13, rankdir=TB, nodesep=0.35, ranksep=0.55,
         pad=0.3, bgcolor="white", newrank=true, label=<<B>{title}</B>>, labelloc=t];
  node  [shape=plain, fontname="Helvetica", fontsize=9];
  edge  [fontname="Helvetica", fontsize=8.5, color="{ink}", fontcolor="{ink}", arrowsize=0.8];
"""

EDGE = {
    "assoc": "arrowhead=vee",
    "compose": "dir=back, arrowtail=diamond",
    "aggregate": "dir=back, arrowtail=odiamond",
    "inherit": "arrowhead=onormal, arrowsize=1.1",
    "depend": "style=dashed, arrowhead=vee",
}


def edge(a: str, b: str, kind: str, label: str = "", tail: str = "", head: str = "") -> str:
    attrs = [EDGE[kind]]
    if label:
        attrs.append(f'label="{label}"')
    if tail:
        attrs.append(f'taillabel="{tail}"')
    if head:
        attrs.append(f'headlabel="{head}"')
    return f"  {a} -> {b} [{', '.join(attrs)}];\n"


def cluster(name: str, title: str, body: str) -> str:
    return (
        f'  subgraph cluster_{name} {{\n    label="{title}"; style="rounded,dashed"; '
        f'color="#b9aa98"; fontsize=11;\n{body}  }}\n'
    )


