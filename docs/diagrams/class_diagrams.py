# ---------------------------------------------------------------- 3. architecture
def _names_box(name: str, stereotype: str, lines: list[str], fill: str = SOFT) -> str:
    uml = UmlClass(name, "", [], attributes=lines)
    return class_node(uml, stereotype=stereotype, fill=fill)


def architecture(c: dict[str, UmlClass]) -> str:
    out = HEADER.format(
        name="architecture", title="Architecture: layers and their classes", ink=INK
    )
    blueprints = sorted(
        p.stem for p in (SRC / "web" / "blueprints").glob("*.py") if p.stem != "__init__"
    )
    services = sorted(
        n for n, k in c.items() if k.module.startswith("services.") and n.endswith("Service")
    )
    repositories = sorted(
        n for n, k in c.items() if n.endswith("Repository") and n != "BaseRepository"
    )
    web = (
        "  "
        + _names_box(
            "Blueprints",
            "Flask blueprints (one per area)",
            [", ".join(blueprints[i : i + 4]) for i in range(0, len(blueprints), 4)],
        )
        + "  "
        + class_node(c["AccessPolicy"], stereotype="deny by default")
        + "  "
        + class_node(c["RateLimiter"])
        + "  "
        + _names_box(
            "Templates",
            "Jinja2 + CSS, no JavaScript",
            ["autoescaped HTML, EN / FR / AR (RTL)", "strict Content-Security-Policy"],
        )
    )
    out += cluster("web", "web/  (HTTP, forms, pages, JSON API)", web)
    svc = (
        "  "
        + class_node(c["Services"], stereotype="composition root (bootstrap)")
        + "  "
        + _names_box("ApplicationServices", "services (role checks, transactions, audit)", services)
        + "  "
        + class_node(c["PasswordHasher"], stereotype="scrypt")
    )
    out += cluster("services", "services/  (use cases)", svc)
    out += cluster(
        "domain",
        "domain/  (pure Python: rules, no database, no web)",
        "  "
        + _names_box(
            "DomainModel",
            "entities, value objects, policies",
            [
                "Reservation, Guest, Room, Bill, Invoice, TaxRule...",
                "see the two domain class diagrams",
            ],
            fill=PAPER,
        ),
    )
    persistence = (
        "  "
        + class_node(c["UnitOfWork"], stereotype="one transaction (BEGIN IMMEDIATE)")
        + "  "
        + _names_box("Repositories", "repositories (SQL with ? parameters)", repositories)
        + "  "
        + class_node(c["BaseRepository"])
    )
    out += cluster("persistence", "persistence/  (SQLite, migrations, backups)", persistence)
    out += '  sqlite [shape=cylinder, style=filled, fillcolor="#ffffff", color="#a0522d", fontsize=10, label="hotel.db\\n(SQLite, WAL)"];\n'
    out += '  cli [shape=box, style="rounded,filled", fillcolor="#ffffff", color="#a0522d", fontsize=10, label="cli.py\\n(hotel ... commands)"];\n'
    out += "".join(
        [
            edge("Blueprints", "AccessPolicy", "depend", "«declares»"),
            edge("Blueprints", "Services", "depend", "«call»"),
            edge("cli", "Services", "depend", "«call»"),
            edge("Services", "ApplicationServices", "compose", "", "1", "*"),
            edge("ApplicationServices", "DomainModel", "depend", "«use»"),
            edge("ApplicationServices", "UnitOfWork", "depend", "«open»"),
            edge("ApplicationServices", "PasswordHasher", "depend", "«use»"),
            edge("UnitOfWork", "Repositories", "compose", "", "1", "*"),
            edge("Repositories", "BaseRepository", "inherit"),
            edge("Repositories", "DomainModel", "depend", "«map rows to»"),
            edge("UnitOfWork", "sqlite", "depend", "«connect»"),
            edge("Blueprints", "Templates", "depend", "«render»"),
            edge("Blueprints", "RateLimiter", "depend", "«API»"),
        ]
    )
    return out + "}\n"


def embed_images(svg: Path) -> None:
    """Put actor.png inside the SVG (data URI): GitHub shows SVGs as images,
    which cannot load a second file."""
    import base64

    data = base64.b64encode((HERE / "actor.png").read_bytes()).decode("ascii")
    text = svg.read_text(encoding="utf-8")
    svg.write_text(text.replace('"actor.png"', f'"data:image/png;base64,{data}"'), encoding="utf-8")


def main() -> None:
    import sys

    if sys.argv[1:2] == ["--embed"]:
        for name in sys.argv[2:]:
            embed_images(Path(name))
        return
    classes = read_classes("", "domain", "services", "persistence", "web")
    classes.update(read_classes("persistence/repositories"))
    for name, text in {
        "classes-domain-stays.dot": domain_stays_and_money(classes),
        "classes-domain-accounts.dot": domain_accounts_and_support(classes),
        "classes-architecture.dot": architecture(classes),
    }.items():
        (HERE / name).write_text(text, encoding="utf-8")
        print("wrote", name)


if __name__ == "__main__":
    main()
